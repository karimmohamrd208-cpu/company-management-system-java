private void loadProjectsTable() {
    DefaultTableModel model = new DefaultTableModel(
        new String[]{"ID", "Project Name", "Status", "Budget"}, 0  // ← 0 rows مش 4
    );
    jTable1.setModel(model);   // ← استبدل الـ model القديم كله



    try {
        String sql = "SELECT p.project_id, p.project_name, p.status, p.price "
                   + "FROM PROJECTS p "
                   + "ORDER BY p.project_id DESC";
        pst    = con.prepareStatement(sql);
        result = pst.executeQuery();
        while (result.next()) {
            ((DefaultTableModel) jTable1.getModel()).addRow(new Object[]{
                result.getInt("project_id"),
                result.getString("project_name"),
                result.getString("status"),
                String.format("%,.0f", result.getDouble("price"))
            });
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

private void loadTasksTable() {
    DefaultTableModel model = new DefaultTableModel(
        new String[]{"ID", "Task", "Project", "Due Date"}, 0
    );
    jTable2.setModel(model);

    try {
        String sql = "SELECT t.task_id, t.title, p.project_name, "
                   + "CONVERT(VARCHAR, t.due_date, 23) AS due_date "
                   + "FROM TASKS t "
                   + "JOIN PROJECTS p ON t.project_id = p.project_id "
                   + "ORDER BY t.due_date ASC";
        pst    = con.prepareStatement(sql);
        result = pst.executeQuery();
        while (result.next()) {
            ((DefaultTableModel) jTable2.getModel()).addRow(new Object[]{
                result.getInt("task_id"),
                result.getString("title"),
                result.getString("project_name"),
                result.getString("due_date")
            });
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}
private void loadStats() {
    if (con == null) return;
    try {
        // Employees
        ResultSet rs = con.createStatement().executeQuery("SELECT COUNT(*) FROM EMPLOYEES");
        if (rs.next()) jLabel10.setText(String.valueOf(rs.getInt(1)));

        // Active Projects
        rs = con.createStatement().executeQuery("SELECT COUNT(*) FROM PROJECTS WHERE status = 'Active'");
        if (rs.next()) jLabel9.setText(String.valueOf(rs.getInt(1)));

        // Clients
        rs = con.createStatement().executeQuery("SELECT COUNT(*) FROM CLIENTS");
        if (rs.next()) jLabel8.setText(String.valueOf(rs.getInt(1)));

        // Pending Tasks
        rs = con.createStatement().executeQuery("SELECT COUNT(*) FROM TASKS WHERE status = 'To Do'");
        if (rs.next()) jLabel7.setText(String.valueOf(rs.getInt(1)));

    } catch (SQLException e) {
        System.out.println("خطأ: " + e.getMessage());
    }
}
